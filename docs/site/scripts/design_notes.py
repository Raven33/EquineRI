#!/usr/bin/env python3
"""Turns the decision log (CONTEXT.md) into the site's Design notes page.

Writes docs/design-notes/decisions.md (git-ignored, rebuilt on every build):
one heading per settled decision with a stable anchor (#p57), so any page can
link [P57](../design-notes/decisions.md#p57) and MkDocs' strict anchor check
catches a reference to a decision that does not exist. P-numbers inside the
text become links. The feature-scope table and the open questions are copied.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from docs_common import CONTEXT_MD, DECISIONS_PAGE, REPO_DIR, write_if_changed  # noqa: E402

ROW = re.compile(r"^\|\s*P(?P<num>\d+)\s*\|(?P<text>.*)\|(?P<source>[^|]*)\|\s*$")
P_REF = re.compile(r"(?<![\w#/\[])P(?P<num>\d{1,3})(?![\w\]])")


def split_cells(row: str) -> list[str]:
    """Splits a Markdown table row on unescaped '|'."""
    cells, cell, i = [], "", 0
    body = row.strip()[1:-1]
    while i < len(body):
        if body[i] == "\\" and i + 1 < len(body) and body[i + 1] == "|":
            cell += "|"
            i += 2
            continue
        if body[i] == "|":
            cells.append(cell.strip())
            cell = ""
        else:
            cell += body[i]
        i += 1
    cells.append(cell.strip())
    return cells


def decisions(text: str) -> list[tuple[int, str, str]]:
    out = []
    for line in text.splitlines():
        if ROW.match(line):
            cells = split_cells(line)
            out.append((int(cells[0][1:]), cells[1], cells[2]))
    return out


def section(text: str, heading: str) -> str:
    """The body of a `## ` or `### ` section, up to the next heading of the same or higher level."""
    lines = text.splitlines()
    level = heading.split(" ", 1)[0]
    for start, line in enumerate(lines):
        if line.startswith(heading):
            body = []
            for line2 in lines[start + 1 :]:
                m = re.match(r"^(#+) ", line2)
                if m and len(m.group(1)) <= len(level):
                    break
                body.append(line2)
            return "\n".join(body).strip()
    return ""


def link_refs(text: str, known: set[int], page: str = "") -> str:
    """P57 -> [P57](#p57), outside inline code, for decisions that exist."""
    parts = re.split(r"(`[^`]*`)", text)
    for i, part in enumerate(parts):
        if part.startswith("`"):
            continue
        parts[i] = P_REF.sub(
            lambda m: f"[P{m.group('num')}]({page}#p{m.group('num')})" if int(m.group("num")) in known else m.group(0),
            part,
        )
    return "".join(parts)


def short_title(text: str) -> str:
    """'Altitude: higher level ...' -> 'Altitude'; empty when no short lead-in."""
    plain = re.sub(r"[*`]", "", text)
    m = re.match(r"^([^:.;(]{3,60})[:.]", plain)
    return m.group(1).strip() if m else ""


def render(context: str) -> str:
    rows = decisions(context)
    known = {num for num, _, _ in rows}
    out = [
        "---",
        "title: Decision log",
        "---",
        "",
        "<!-- Generated by docs/site/scripts/design_notes.py from CONTEXT.md. Do not edit: edit CONTEXT.md. -->",
        "",
        "# Decision log",
        "",
        "Every design decision of EquineRI has a number, P1, P2, and so on. Pages across this site cite them",
        "under *Related decisions*. This page is generated from the repository's `CONTEXT.md`, the decision",
        "log written during the design phase and updated as the implementation settles details.",
        "",
        "Decisions written before P81 sometimes use method syntax (`cmd.discard(...)`); the API style",
        link_refs("is plain structs and free functions (P81 to P88).", known),
        "",
        "## Settled decisions",
        "",
    ]
    for num, text, source in rows:
        title = short_title(text)
        out.append(f"### P{num}{': ' + title if title else ''} {{#p{num}}}")
        out.append("")
        out.append(link_refs(text, known))
        out.append("")
        out.append(f"*Source: {source}*")
        out.append("")
    scope = section(context, "### Feature scope")
    if scope:
        out += ["## Feature scope", "", link_refs(scope, known), ""]
    questions = section(context, "## 5. Open questions")
    if questions:
        out += ["## Open questions", "", link_refs(questions, known), ""]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    content = render(CONTEXT_MD.read_text(encoding="utf-8"))
    write_if_changed(DECISIONS_PAGE, content)
    print(f"design_notes: {content.count('### P')} decisions -> {DECISIONS_PAGE.relative_to(REPO_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
